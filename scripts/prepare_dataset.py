"""Convert raw landscape videos into training tuples for the learned predictor.

For every frame pair (t, t + delta) of every input video the script writes::

    out_root/<video_stem>_<frame_index>/
        image.png   # frame t (RGB)
        sketch.png  # white-to-black streamline rendering of the predicted flow
        mask.png    # fluid region mask (Grounded-SAM, prompt-driven)
        flow.npy    # H x W x 2 float32 RAFT flow from frame t to frame t+delta

Usage::

    python scripts/prepare_dataset.py \
        --videos data/raw/landscape/*.mp4 \
        --output data/training/landscape \
        --prompt "water" \
        --frame-stride 5 \
        --max-pairs-per-video 6

RAFT (small variant) is loaded from ``torchvision.models.optical_flow`` so no
extra repository checkout is required. The fluid mask is generated by reusing
the project's Grounded-SAM backend in ``src.fluid_mask.refine_mask`` so the
training distribution matches the inference distribution.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Iterable, List, Tuple

import cv2
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Build training tuples from landscape videos.")
    parser.add_argument("--videos", nargs="+", required=True, help="Glob(s) or paths of source videos.")
    parser.add_argument("--output", type=Path, required=True, help="Directory to write training samples.")
    parser.add_argument(
        "--prompt",
        type=str,
        default="water. river. sea. waterfall.",
        help="Text query for Grounded-SAM mask extraction.",
    )
    parser.add_argument("--frame-stride", type=int, default=5, help="Number of frames between paired frames.")
    parser.add_argument(
        "--max-pairs-per-video",
        type=int,
        default=8,
        help="Maximum number of training pairs to extract per source video.",
    )
    parser.add_argument("--image-size", type=int, default=384, help="Output spatial size for stored frames.")
    parser.add_argument(
        "--num-strokes",
        type=int,
        default=3,
        help="Number of streamlines to render per motion sketch.",
    )
    parser.add_argument(
        "--device",
        type=str,
        default=None,
        help='Force RAFT device: "cuda", "mps" or "cpu".',
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    args.output.mkdir(parents=True, exist_ok=True)

    import torch
    import torchvision
    from torchvision.models.optical_flow import Raft_Small_Weights, raft_small

    from src.motion_field.networks import resolve_device
    from src.fluid_mask.refine_mask import refine_fluid_mask

    device = resolve_device(args.device)
    print(f"Using device: {device}")

    weights = Raft_Small_Weights.DEFAULT
    raft = raft_small(weights=weights, progress=True).to(device).eval()
    transforms = weights.transforms()

    video_paths = list(_expand_paths(args.videos))
    if not video_paths:
        raise SystemExit("No videos matched the provided patterns.")
    print(f"Discovered {len(video_paths)} videos.")

    sample_index = 0
    for video_path in video_paths:
        print(f"\n=== {video_path} ===")
        try:
            samples_written = _process_video(
                video_path=video_path,
                output_root=args.output,
                raft=raft,
                transforms=transforms,
                device=device,
                prompt=args.prompt,
                frame_stride=args.frame_stride,
                max_pairs=args.max_pairs_per_video,
                image_size=args.image_size,
                num_strokes=args.num_strokes,
                sample_index_start=sample_index,
            )
            sample_index += samples_written
        except Exception as error:  # noqa: BLE001 - keep pipeline going if a clip fails
            print(f"  ! skipped {video_path.name}: {error}")

    print(f"\nDone. Total samples written: {sample_index}")


def _expand_paths(patterns: Iterable[str]) -> Iterable[Path]:
    for pattern in patterns:
        path = Path(pattern)
        if path.exists() and path.is_file():
            yield path
            continue
        # Treat as glob
        matches = list(Path().glob(pattern)) or list(path.parent.glob(path.name))
        for match in matches:
            if match.is_file():
                yield match


def _process_video(
    video_path: Path,
    output_root: Path,
    raft,
    transforms,
    device,
    prompt: str,
    frame_stride: int,
    max_pairs: int,
    image_size: int,
    num_strokes: int,
    sample_index_start: int,
) -> int:
    import torch

    capture = cv2.VideoCapture(str(video_path))
    if not capture.isOpened():
        raise RuntimeError("could not open video")

    frame_count = int(capture.get(cv2.CAP_PROP_FRAME_COUNT))
    if frame_count < frame_stride + 2:
        capture.release()
        raise RuntimeError(f"video has too few frames ({frame_count}).")

    indices = np.linspace(0, frame_count - frame_stride - 1, num=max_pairs, dtype=int).tolist()
    samples_written = 0

    for pair_idx, start_idx in enumerate(indices):
        capture.set(cv2.CAP_PROP_POS_FRAMES, int(start_idx))
        ok, frame_a = capture.read()
        if not ok:
            continue
        capture.set(cv2.CAP_PROP_POS_FRAMES, int(start_idx + frame_stride))
        ok, frame_b = capture.read()
        if not ok:
            continue

        frame_a = cv2.cvtColor(frame_a, cv2.COLOR_BGR2RGB)
        frame_b = cv2.cvtColor(frame_b, cv2.COLOR_BGR2RGB)

        frame_a = _resize_keep(frame_a, image_size)
        frame_b = _resize_keep(frame_b, image_size)

        flow = _estimate_flow(raft, transforms, frame_a, frame_b, device)
        mask = refine_fluid_mask(frame_a, prompt)
        if int((mask > 0).sum()) < image_size * image_size * 0.005:
            print(f"  - pair {pair_idx}: mask too small, skipping.")
            continue

        sketch = _flow_to_sketch(flow, mask, num_strokes=num_strokes, seed=sample_index_start + samples_written)

        sample_dir = output_root / f"{video_path.stem}_{start_idx:06d}"
        sample_dir.mkdir(parents=True, exist_ok=True)
        cv2.imwrite(str(sample_dir / "image.png"), cv2.cvtColor(frame_a, cv2.COLOR_RGB2BGR))
        cv2.imwrite(str(sample_dir / "sketch.png"), cv2.cvtColor(sketch, cv2.COLOR_RGB2BGR))
        cv2.imwrite(str(sample_dir / "mask.png"), mask)
        np.save(sample_dir / "flow.npy", flow.astype(np.float32))
        samples_written += 1
        print(f"  + {sample_dir.name}")

    capture.release()
    return samples_written


def _resize_keep(image: np.ndarray, size: int) -> np.ndarray:
    """Centre-crop to a square then resize to ``size``."""
    h, w = image.shape[:2]
    side = min(h, w)
    top = (h - side) // 2
    left = (w - side) // 2
    cropped = image[top : top + side, left : left + side]
    return cv2.resize(cropped, (size, size), interpolation=cv2.INTER_AREA)


def _estimate_flow(raft, transforms, frame_a: np.ndarray, frame_b: np.ndarray, device) -> np.ndarray:
    import torch

    image_a = torch.from_numpy(frame_a).permute(2, 0, 1).float()
    image_b = torch.from_numpy(frame_b).permute(2, 0, 1).float()
    batch_a, batch_b = transforms(image_a.unsqueeze(0), image_b.unsqueeze(0))
    batch_a = batch_a.to(device)
    batch_b = batch_b.to(device)
    with torch.no_grad():
        predictions = raft(batch_a, batch_b)
    flow_tensor = predictions[-1][0].detach().cpu().numpy()
    flow = np.transpose(flow_tensor, (1, 2, 0))
    return flow.astype(np.float32)


def _flow_to_sketch(flow: np.ndarray, mask: np.ndarray, num_strokes: int, seed: int) -> np.ndarray:
    """Render a few streamlines from the flow with a white-to-black gradient."""
    rng = np.random.default_rng(seed)
    h, w = mask.shape[:2]
    sketch = np.full((h, w, 3), 255, dtype=np.uint8)
    valid = np.argwhere(mask > 0)
    if len(valid) == 0:
        return sketch

    step_size = 1.5
    max_steps = 80
    for _ in range(max(1, num_strokes)):
        seed_idx = rng.integers(0, len(valid))
        y, x = float(valid[seed_idx][0]), float(valid[seed_idx][1])
        path: List[Tuple[float, float]] = [(y, x)]
        for _step in range(max_steps):
            iy, ix = int(round(y)), int(round(x))
            if iy < 0 or iy >= h or ix < 0 or ix >= w or mask[iy, ix] == 0:
                break
            vec = flow[iy, ix]
            magnitude = float(np.linalg.norm(vec))
            if magnitude < 1e-3:
                break
            x += vec[0] / magnitude * step_size
            y += vec[1] / magnitude * step_size
            path.append((y, x))

        if len(path) < 4:
            continue
        path_arr = np.array(path)
        for i in range(len(path_arr) - 1):
            ratio = i / max(len(path_arr) - 2, 1)
            grey = int(round(255 * (1.0 - ratio)))
            p0 = (int(round(path_arr[i, 1])), int(round(path_arr[i, 0])))
            p1 = (int(round(path_arr[i + 1, 1])), int(round(path_arr[i + 1, 0])))
            cv2.line(sketch, p0, p1, (grey, grey, grey), 1, lineType=cv2.LINE_AA)

    return sketch


if __name__ == "__main__":
    main()
